#!/usr/bin/env bash
# initializeCommand: runs on the host (rrdev) before the dev stack starts.
# 1. Makes sure the project's Claude Code login volume (<app>-claude-config) exists. It is an
#    external volume, so "docker compose down -v" never deletes it. Compose reads its name
#    from CLAUDE_VOLUME in .env.
# 2. For each service enabled under "include:" in compose.yaml, appends services/<name>.env.tmpl
#    to .env once, replacing each __GEN_<NAME>__ with a random value (same name = same value).
# .env is gitignored. To reset one service: delete its section here AND its data volume.
set -euo pipefail
cd "$(dirname "$0")"
umask 077
[ -f .env ] || echo "# Generated by init-env.sh. Dev only, never commit." > .env

# <app> = the repo folder name, lowercased; anything Docker rejects in a volume name becomes "-",
# and the name must start with a letter or digit.
app=$(basename "$(cd .. && pwd)" | tr '[:upper:]' '[:lower:]' | tr -c 'a-z0-9_.\n-' '-' | sed 's/^[^a-z0-9]*//')
[ -n "$app" ] || app=project
grep -q '^CLAUDE_VOLUME=' .env || printf 'CLAUDE_VOLUME=%s-claude-config\n' "$app" >> .env
# Use the name Compose will use (.env wins, e.g. after a folder rename).
vol=$(sed -n 's/^CLAUDE_VOLUME=//p' .env | tail -n1)
docker volume inspect "$vol" >/dev/null 2>&1 || docker volume create "$vol" >/dev/null
for svc in $(grep -oE '^[[:space:]]+-[[:space:]]+services/[a-z0-9-]+\.yaml' compose.yaml \
             | sed -E 's|.*services/([a-z0-9-]+)\.yaml|\1|'); do
  grep -q "^# service: ${svc}\$" .env && continue
  tmpl="services/${svc}.env.tmpl"
  [ -f "$tmpl" ] || { echo "init-env: missing $tmpl" >&2; exit 1; }
  block=$(cat "$tmpl")
  for ph in $(grep -oE '__GEN_[A-Z0-9_]+__' "$tmpl" | sort -u); do
    block=${block//$ph/$(openssl rand -hex 24)}
  done
  printf '\n# service: %s\n%s\n' "$svc" "$block" >> .env
  echo "init-env: generated credentials for $svc"
done
